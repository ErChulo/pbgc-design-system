#!/usr/bin/env node
// Generates tokens/tokens.css and tokens/contrast-report.md from tokens/tokens.json,
// and FAILS (exit 1) if any declared color pair is below its WCAG minimum.
// Zero dependencies. Runs on any Node >= 18. No network.
//
// Usage: node scripts/build-tokens.mjs [--check]   (--check = validate only, write nothing)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const checkOnly = process.argv.includes('--check');

// ---------- helpers ----------
const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? o : o[k]), obj);

function resolve(value, seen = new Set()) {
  if (typeof value !== 'string') return value;
  const m = value.match(/^\{(.+)\}$/);
  if (!m) return value;
  if (seen.has(m[1])) throw new Error(`Circular alias: ${m[1]}`);
  seen.add(m[1]);
  const target = get(tokens, m[1]);
  if (target === undefined) throw new Error(`Unresolved alias: ${value}`);
  return resolve(typeof target === 'object' && '$value' in target ? target.$value : target, seen);
}

const lin = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
function luminance(hex) {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const flatten = (obj, prefix = []) =>
  Object.entries(obj).flatMap(([k, v]) => {
    if (k.startsWith('$')) return [];
    return typeof v === 'object' && v !== null && !('$value' in v)
      ? flatten(v, [...prefix, k])
      : [[[...prefix, k], v]];
  });

// ---------- resolve themes ----------
const themes = {};
for (const name of ['light', 'dark']) {
  themes[name] = Object.fromEntries(
    flatten(tokens.theme[name]).map(([path, v]) => [path.join('.'), resolve(v)])
  );
}

function colorFor(themeName, ref) {
  if (ref.startsWith('palette.')) return resolve(get(tokens, ref).$value);
  const c = themes[themeName][ref];
  if (!c) throw new Error(`Unknown token in pair: ${ref}`);
  return c;
}

// ---------- contrast validation ----------
let failures = 0;
const rows = [];
for (const themeName of ['light', 'dark']) {
  for (const p of tokens.pairs) {
    // Brand-red pair is theme independent; report once.
    if (p.bg.startsWith('palette.') && themeName === 'dark') continue;
    const fg = colorFor(themeName, p.fg);
    const bg = colorFor(themeName, p.bg);
    const r = ratio(fg, bg);
    const pass = r >= p.min;
    if (!pass) failures++;
    rows.push({ themeName, ...p, fgHex: fg, bgHex: bg, r, pass });
  }
}

const report = [
  '# Contrast report',
  '',
  '> GENERATED by `scripts/build-tokens.mjs` from `tokens/tokens.json`. Do not edit by hand.',
  '> Ratios use the WCAG 2.x relative-luminance formula. Thresholds: 4.5 for text, 3 for UI boundaries, icons and focus indicators.',
  '',
  `**Result: ${failures === 0 ? 'ALL PAIRS PASS' : failures + ' PAIR(S) FAIL'}** (${rows.length} checks, light and dark themes).`,
  '',
  '| Theme | Pair | Foreground | Background | Ratio | Min | Result |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((x) =>
    `| ${x.themeName} | ${x.label} | \`${x.fgHex}\` | \`${x.bgHex}\` | ${x.r.toFixed(2)} | ${x.min} | ${x.pass ? 'pass' : '**FAIL**'} |`
  ),
  '',
  '## Brand palette on white — what may carry text',
  '',
  'Computed for every palette color so nobody has to guess which brand colors are text-safe.',
  '',
  '| Color | HEX | vs white | Text (4.5) | UI/icon (3) |',
  '|---|---|---|---|---|',
  ...flatten(tokens.palette)
    .map(([path, v]) => ({ name: path.join('.'), hex: v.$value }))
    .filter((c) => !c.name.includes('night') && !c.name.includes('tint'))
    .map((c) => {
      const r = ratio(c.hex, '#FFFFFF');
      return `| ${c.name} | \`${c.hex}\` | ${r.toFixed(2)} | ${r >= 4.5 ? 'yes' : 'no'} | ${r >= 3 ? 'yes' : 'no'} |`;
    }),
  '',
].join('\n');

// ---------- emit CSS ----------
const cssVars = (obj, indent = '  ') =>
  Object.entries(obj).map(([k, v]) => `${indent}--pbgc-${k.replace(/\./g, '-')}: ${v};`).join('\n');

const staticVars = Object.fromEntries(
  flatten(tokens.static)
    .filter(([path]) => !path[path.length - 1].endsWith('-note'))
    .map(([path, v]) => [path.join('-'), v])
);
const paletteVars = Object.fromEntries(
  flatten(tokens.palette).map(([path, v]) => [`color-${path.join('-')}`, v.$value])
);

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. DO NOT EDIT. */
/* PBGC design tokens v${'1.8.0'} */

:root {
  /* --- palette (raw brand values; prefer semantic tokens in components) --- */
${cssVars(paletteVars)}

  /* --- static tokens --- */
${cssVars(staticVars)}

  /* --- light theme (default) --- */
${cssVars(themes.light)}
  color-scheme: light;
}

/* Provisional dark theme. Not in the PBGC style guide; see OPEN-QUESTIONS.md Q6. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${cssVars(themes.dark, '    ')}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${cssVars(themes.dark)}
  color-scheme: dark;
}

/* Reduced motion is honored at the token level: every transition and animation
   in the system reads these, so nothing can forget to check the preference. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --pbgc-motion-duration-fast: 0.01ms;
    --pbgc-motion-duration-base: 0.01ms;
  }
}
`;

if (!checkOnly) {
  writeFileSync(join(root, 'tokens/tokens.css'), css);
  writeFileSync(join(root, 'tokens/contrast-report.md'), report);
}
console.log(`${rows.length} contrast checks, ${failures} failure(s).`);
for (const x of rows.filter((r) => !r.pass)) {
  console.error(`FAIL [${x.themeName}] ${x.label}: ${x.fgHex} on ${x.bgHex} = ${x.r.toFixed(2)} (min ${x.min})`);
}
process.exit(failures ? 1 : 0);

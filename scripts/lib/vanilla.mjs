// Turns src/behaviors/index.js (an ES module) into a classic-script IIFE that defines window.PBGC.
// Shared by build-vanilla.mjs (dist/pbgc.js) and build-reference.mjs (inlined into the single-file page),
// so the file apps copy and the file the tests exercise are produced by the same code.
export function buildVanilla(src) {
  const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map((m) => m[1]);
  const body = src
    .replace(/^export (function|const) /gm, '$1 ')
    .replace(/^export \{[^}]*\};?\s*$/gm, '');
  return `/* PBGC behaviors, framework-free build. GENERATED by scripts/build-vanilla.mjs from src/behaviors/index.js. DO NOT EDIT. */
(function () {
'use strict';
${body}
window.PBGC = { ${names.join(', ')}, default: init };
})();
`;
}
